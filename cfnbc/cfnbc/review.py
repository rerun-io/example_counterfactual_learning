"""Generate review lists of viewer deep links from catalog queries.

    python -m cfnbc.review demos [--seed 0] [--out results/reviews/demo_review.md]

Deep links (`DatasetEntry.segment_url`) embed the catalog URL and dataset id, so they only stay valid against a
persistent catalog (the server from `python -m cfnbc.serve`, or a Rerun Hub). Without
it, the list falls back to `rerun <files>` commands that open the same segment and layers locally.
"""
from __future__ import annotations

import argparse
import random
from pathlib import Path

import pandas as pd

from cfnbc import hub, query as Q
from cfnbc import schema as S

ROOT = Path(__file__).resolve().parents[2]


class Linker:
    def __init__(self, client, dataset: str):
        self.persistent = hub.catalog_url() is not None
        self.ds = client.get_dataset(dataset)
        self.dataset = dataset

    def link(self, segment_id: str, start: int | None = None, end: int | None = None) -> str:
        if self.persistent:
            if start is None:  # SDK 0.38: timeline without start renders an int64-min timestamp in the URL
                return self.ds.segment_url(segment_id)
            return self.ds.segment_url(segment_id, timeline=S.TIMELINE_STEP, start=start, end=end)
        files = [p for p in (S.rerun_root() / "demos" / f"{segment_id}.rrd", S.rerun_root() / "qa" / f"{segment_id}.rrd")
                 if p.exists()] if self.dataset == S.DATASET_DEMOS else [S.rerun_root() / "rollouts" / f"{segment_id}.rrd"]
        rng = f" (steps {start}-{end})" if start is not None else ""
        return "`rerun " + " ".join(str(p.relative_to(ROOT)) for p in files) + "`" + rng


def qa_table(client) -> pd.DataFrame:
    df = Q._props(client, S.DATASET_DEMOS, "qa").rename(columns={"rerun_segment_id": "segment_id"})
    return df.dropna(subset=["max_stage"]).reset_index(drop=True)


def demos(seed: int, out: Path) -> None:
    with hub.open_catalog() as client:
        qa = qa_table(client)
        L = Linker(client, S.DATASET_DEMOS)
        lines = ["# Demo review (step 4)", "",
                 f"Generated by `python -m cfnbc.review demos`. Catalog: {hub.catalog_url() or 'local files'}.", "",
                 "Blueprint: `rerun/blueprints/cube_demos.rbl` (camera, action/qpos, QA reward stage, jerk, cube height).",
                 "", "## Checklist: first / last / random", ""]
        ids = sorted(qa.segment_id)
        pick = [ids[0], ids[-1], random.Random(seed).choice(ids[1:-1])]
        for sid in pick:
            lines.append(f"- [ ] {sid}: {L.link(sid)}")

        qa = qa.assign(lift_gap=qa.first_lift - qa.first_touch)
        lines += ["", "## QA flags", "", "### Lift registered within <10 steps of first touch",
                  "Stage 2 ('lifted') fires when the cube's table contact drops for a step while a finger presses it; "
                  "the cube is still at table height. Upstream reward artifact (max-over-episode scoring).", ""]
        for r in qa[qa.lift_gap < 10].sort_values("lift_gap").itertuples():
            lines.append(f"- [ ] {r.segment_id}: touch@{r.first_touch} lift@{r.first_lift}: "
                         f"{L.link(r.segment_id, r.first_touch - 10, r.first_lift + 15)}")

        lines += ["", "### Extremes per metric", "", "| metric | min (segment) | max (segment) | spread |", "|---|---|---|---|"]
        metrics = ["first_touch", "first_lift", "first_transfer", "max_jerk", "gripper_chatter_left",
                   "gripper_chatter_right", "cube_max_height", "min_joint_limit_margin", "blank_frames", "duplicate_frames"]
        for m in metrics:
            lo, hi = qa.loc[qa[m].idxmin()], qa.loc[qa[m].idxmax()]
            lines.append(f"| {m} | {lo[m]:.4g} ({lo.segment_id}) | {hi[m]:.4g} ({hi.segment_id}) | {hi[m] - lo[m]:.4g} |")
        lines += ["", "Links to the extreme segments:", ""]
        for m in ("max_jerk", "first_touch", "cube_max_height"):
            for sid in {qa.loc[qa[m].idxmin()].segment_id, qa.loc[qa[m].idxmax()].segment_id}:
                lines.append(f"- [ ] {m}: {sid}: {L.link(sid)}")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("\n".join(lines) + "\n")
        print(f"wrote {out}")


def preservation(out: Path) -> None:
    """Review list for flagged task-preservation checks (table `task_preservation`)."""
    with hub.open_catalog() as client:
        df = client.get_table("task_preservation").reader().to_pandas()
        L = Linker(client, S.DATASET_DEMOS)
        flagged = df[df.flag].sort_values("cube_distractor_m")
        lines = ["# Task-preservation review", "",
                 f"Generated by `python -m cfnbc.review preservation`. Catalog: {hub.catalog_url() or 'local files'}.", "",
                 "Open with layers `scene3d` + `scene3d_<condition>` (robot + nuisance geometry, `/checks/*` scalars).", "",
                 "| condition | flagged / episodes | worst cube overlap (mm) | worst finger clearance (mm) | max occlusion |",
                 "|---|---|---|---|---|"]
        for c, g in df.groupby("condition"):
            lines.append(f"| {c} | {int(g.flag.sum())} / {len(g)} | {max(0, -1000 * g.cube_distractor_m.min()):.1f} | "
                         f"{1000 * g.min_clearance_m.min():.1f} | {g.occl_nuisance_max.max():.3f} |")
        lines += ["", "## Worst flagged cases", ""]
        for r in flagged.head(15).itertuples():
            t = r.cube_distractor_step if r.cube_distractor_m < 0 else r.clearance_step
            lines.append(f"- [ ] {r.segment_id} {r.condition}: cube {1000 * r.cube_distractor_m:.1f} mm, finger "
                         f"{1000 * r.min_clearance_m:.1f} mm @ step {t}: {L.link(r.segment_id, max(0, t - 15), t + 15)}")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("\n".join(lines) + "\n")
        print(f"wrote {out}")


def main() -> None:
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("demos")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--out", default=str(ROOT / "results" / "reviews" / "demo_review.md"))
    p2 = sub.add_parser("preservation")
    p2.add_argument("--out", default=str(ROOT / "results" / "reviews" / "task_preservation_review.md"))
    args = parser.parse_args()
    if args.cmd == "demos":
        demos(args.seed, Path(args.out))
    elif args.cmd == "preservation":
        preservation(Path(args.out))


if __name__ == "__main__":
    main()
